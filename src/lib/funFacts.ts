// Hands out facts in a shuffled order, with no repeats until every fact has
// been seen. The order is saved per kid in localStorage, so it survives
// closing the game. If storage is blocked, it just picks a random fact.
export function nextFunFact(): string {
  const profile = (() => { try { return localStorage.getItem("levelup_active_profile") ?? "guest"; } catch { return "guest"; } })();
  const key = `levelup_facts_${profile}`;
  try {
    const saved = JSON.parse(localStorage.getItem(key) ?? "null") as { order: number[]; pos: number } | null;
    let state = saved;
    if (!state || state.order.length !== FUN_FACTS.length || state.pos >= state.order.length) {
      const order = FUN_FACTS.map((_, i) => i);
      for (let i = order.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [order[i], order[j]] = [order[j], order[i]];
      }
      state = { order, pos: 0 };
    }
    const fact = FUN_FACTS[state.order[state.pos]];
    localStorage.setItem(key, JSON.stringify({ order: state.order, pos: state.pos + 1 }));
    return fact;
  } catch {
    return FUN_FACTS[Math.floor(Math.random() * FUN_FACTS.length)];
  }
}

// Tricks for a specific number in a times-table question.
const TIMES_TRICKS: Record<number, string> = {
  2:  "For × 2, just double the number.",
  4:  "For × 4, double it and then double it again.",
  5:  "For × 5, count by fives.",
  9:  "For × 9, do × 10 and then take one group away.",
  10: "For × 10, add a zero to the end.",
  11: "For × 11 with a single digit, just write the digit twice: 11 × 7 = 77.",
};

export function hintFor(question: string): string {
  const type = question.includes("×") ? "multiply" : question.includes("−") ? "subtract" : "add";
  const list = [...HINTS[type]];
  if (type === "multiply") {
    for (const n of (question.match(/\d+/g) ?? []).map(Number)) {
      if (TIMES_TRICKS[n]) list.push(TIMES_TRICKS[n], TIMES_TRICKS[n]);
    }
  }
  return list[Math.floor(Math.random() * list.length)];
}
